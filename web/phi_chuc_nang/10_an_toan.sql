-- AT01: sao lưu QLBANVE_HQ, phục hồi sang QLBANVE_HQ_PHUCHOI, so số dòng 10 bảng và CHECKSUM_AGG của VE, TAIKHOAN.
-- Chạy trên master: sqlcmd -S localhost\SQLEXPRESS -E -C -b -d master -v TepSaoLuu="D:\...\QLBANVE_HQ.bak" -i 10_an_toan.sql
-- Không xóa QLBANVE_HQ_PHUCHOI ở đây; 10_an_toan.ps1 xóa sau khi lưu kết quả.
SET NOCOUNT ON;
SET XACT_ABORT ON;
IF DB_ID(N'QLBANVE_HQ') IS NULL THROW 50000, 'Khong co QLBANVE_HQ', 1;
IF DB_ID(N'QLBANVE_HQ_PHUCHOI') IS NOT NULL THROW 50000, 'QLBANVE_HQ_PHUCHOI da ton tai, hay xoa truoc', 1;

DECLARE @t0 datetime2(3) = SYSDATETIME();
BACKUP DATABASE [QLBANVE_HQ] TO DISK = N'$(TepSaoLuu)' WITH INIT, CHECKSUM;
DECLARE @t1 datetime2(3) = SYSDATETIME();

DECLARE @duongDan nvarchar(400) = CAST(SERVERPROPERTY('InstanceDefaultDataPath') AS nvarchar(400));
DECLARE @move nvarchar(max) = N'';
SELECT @move += N', MOVE N''' + REPLACE(name, '''', '''''') + N''' TO N''' + @duongDan + N'QLBANVE_HQ_PHUCHOI_'
    + CAST(file_id AS nvarchar(10)) + CASE type WHEN 1 THEN N'.ldf' ELSE N'.mdf' END + N''''
FROM QLBANVE_HQ.sys.database_files;
DECLARE @lenh nvarchar(max) = N'RESTORE DATABASE [QLBANVE_HQ_PHUCHOI] FROM DISK = N''$(TepSaoLuu)'' WITH CHECKSUM' + @move + N';';
EXEC (@lenh);
DECLARE @t2 datetime2(3) = SYSDATETIME();

DECLARE @so TABLE (Bang sysname, Goc bigint, PhucHoi bigint);
INSERT @so SELECT 'SANBAY', (SELECT COUNT_BIG(*) FROM QLBANVE_HQ.dbo.SANBAY), (SELECT COUNT_BIG(*) FROM QLBANVE_HQ_PHUCHOI.dbo.SANBAY);
INSERT @so SELECT 'CHUYENBAY', (SELECT COUNT_BIG(*) FROM QLBANVE_HQ.dbo.CHUYENBAY), (SELECT COUNT_BIG(*) FROM QLBANVE_HQ_PHUCHOI.dbo.CHUYENBAY);
INSERT @so SELECT 'CHITIETSANBAYTRUNGGIAN', (SELECT COUNT_BIG(*) FROM QLBANVE_HQ.dbo.CHITIETSANBAYTRUNGGIAN), (SELECT COUNT_BIG(*) FROM QLBANVE_HQ_PHUCHOI.dbo.CHITIETSANBAYTRUNGGIAN);
INSERT @so SELECT 'HANGVE', (SELECT COUNT_BIG(*) FROM QLBANVE_HQ.dbo.HANGVE), (SELECT COUNT_BIG(*) FROM QLBANVE_HQ_PHUCHOI.dbo.HANGVE);
INSERT @so SELECT 'GHETHEOHANG', (SELECT COUNT_BIG(*) FROM QLBANVE_HQ.dbo.GHETHEOHANG), (SELECT COUNT_BIG(*) FROM QLBANVE_HQ_PHUCHOI.dbo.GHETHEOHANG);
INSERT @so SELECT 'HANHKHACH', (SELECT COUNT_BIG(*) FROM QLBANVE_HQ.dbo.HANHKHACH), (SELECT COUNT_BIG(*) FROM QLBANVE_HQ_PHUCHOI.dbo.HANHKHACH);
INSERT @so SELECT 'PHIEUDATCHO', (SELECT COUNT_BIG(*) FROM QLBANVE_HQ.dbo.PHIEUDATCHO), (SELECT COUNT_BIG(*) FROM QLBANVE_HQ_PHUCHOI.dbo.PHIEUDATCHO);
INSERT @so SELECT 'VE', (SELECT COUNT_BIG(*) FROM QLBANVE_HQ.dbo.VE), (SELECT COUNT_BIG(*) FROM QLBANVE_HQ_PHUCHOI.dbo.VE);
INSERT @so SELECT 'THAMSOQUYDINH', (SELECT COUNT_BIG(*) FROM QLBANVE_HQ.dbo.THAMSOQUYDINH), (SELECT COUNT_BIG(*) FROM QLBANVE_HQ_PHUCHOI.dbo.THAMSOQUYDINH);
INSERT @so SELECT 'TAIKHOAN', (SELECT COUNT_BIG(*) FROM QLBANVE_HQ.dbo.TAIKHOAN), (SELECT COUNT_BIG(*) FROM QLBANVE_HQ_PHUCHOI.dbo.TAIKHOAN);
DECLARE @ck TABLE (Bang sysname, Goc int, PhucHoi int);
INSERT @ck SELECT 'VE', (SELECT CHECKSUM_AGG(BINARY_CHECKSUM(*)) FROM QLBANVE_HQ.dbo.VE), (SELECT CHECKSUM_AGG(BINARY_CHECKSUM(*)) FROM QLBANVE_HQ_PHUCHOI.dbo.VE);
INSERT @ck SELECT 'TAIKHOAN', (SELECT CHECKSUM_AGG(BINARY_CHECKSUM(*)) FROM QLBANVE_HQ.dbo.TAIKHOAN), (SELECT CHECKSUM_AGG(BINARY_CHECKSUM(*)) FROM QLBANVE_HQ_PHUCHOI.dbo.TAIKHOAN);
DECLARE @t3 datetime2(3) = SYSDATETIME();

SELECT CONCAT('SODONG|', Bang, '|', Goc, '|', PhucHoi, '|', CASE WHEN Goc = PhucHoi THEN 'khop' ELSE 'KHAC' END) FROM @so;
SELECT CONCAT('CHECKSUM|', Bang, '|', Goc, '|', PhucHoi, '|', CASE WHEN Goc = PhucHoi THEN 'khop' ELSE 'KHAC' END) FROM @ck;
SELECT TOP (1) CONCAT('SAOLUU|byte ', backup_size, '|bat dau ', CONVERT(varchar(23), backup_start_date, 121), '|ket thuc ', CONVERT(varchar(23), backup_finish_date, 121))
FROM msdb.dbo.backupset WHERE database_name = N'QLBANVE_HQ' ORDER BY backup_set_id DESC;
SELECT CONCAT('THOIGIAN|sao luu ms ', DATEDIFF(ms, @t0, @t1), '|phuc hoi ms ', DATEDIFF(ms, @t1, @t2), '|so sanh ms ', DATEDIFF(ms, @t2, @t3), '|tong ms ', DATEDIFF(ms, @t0, @t3));
